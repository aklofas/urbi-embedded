#!/usr/bin/env python3
"""urbi-rosgen.py — emit self-contained C structs + marshal/unmarshal + a
type registry for a fixed message manifest. v0.12.1: scalar + nested-scalar
+ string + sequence (mock-path, fixed-cap).
Usage: urbi-rosgen.py <manifest.json> <out.gen.c> <out.gen.h>"""
import json, sys

PRIM_C = {"bool": "uint8_t", "int32": "int32_t", "uint32": "uint32_t",
          "int64": "int64_t", "float32": "float", "float64": "double"}

SLOT_READ = {"bool": "urbi_value_as_bool", "int32": "urbi_value_as_int",
             "uint32": "urbi_value_as_int", "int64": "urbi_value_as_int",
             "float32": "urbi_value_as_float", "float64": "urbi_value_as_float"}
CCAST = {"bool": "(uint8_t)", "int32": "(int32_t)", "uint32": "(uint32_t)",
         "int64": "(int64_t)", "float32": "(float)", "float64": "(double)"}
MAKE = {"bool": "urbi_make_bool", "int32": "urbi_make_int",
        "uint32": "urbi_make_int", "int64": "urbi_make_int",
        "float32": "urbi_make_float", "float64": "urbi_make_float"}

# Fixed capacities for the mock-only self-contained struct representation.
# The rcl path (--target rcl, Phase B) uses unbounded rosidl heap fields.
MOCK_STRING_CAP = 256
MOCK_SEQ_CAP    = 64

def is_seq(ftype):
    """Return True if ftype is a sequence kind (e.g. 'float32[]')."""
    return ftype.endswith("[]")

def seq_elem(ftype):
    """Return the element type of a sequence field (e.g. 'float32[]' -> 'float32')."""
    return ftype[:-2]

def cident(type_name):
    return "urbi_ros__" + type_name.replace("/", "__")

def field_ctype(ftype):
    if ftype in PRIM_C:
        return PRIM_C[ftype]
    return "struct " + cident(ftype)   # nested message

def toposort(msgs):
    seen, order = set(), []
    def visit(n):
        if n in seen or n not in msgs: return
        for _, ft in msgs[n]:
            elem = seq_elem(ft) if is_seq(ft) else ft
            if elem not in PRIM_C and elem != "string": visit(elem)
        seen.add(n); order.append(n)
    for n in msgs: visit(n)
    return order

def emit_header(msgs):
    out = ["/* GENERATED by tools/urbi-rosgen.py - do not edit. */",
           "#ifndef UROS_MSGS_GEN_H", "#define UROS_MSGS_GEN_H",
           "#ifdef URBI_ENABLE_ROS2", "#include <stdint.h>",
           "#include <string.h>  /* memcpy / strncpy */", ""]
    for name in toposort(msgs):
        out.append("struct %s {" % cident(name))
        for fname, ftype in msgs[name]:
            if ftype == "string":
                # mock-only: fixed 256-byte buffer; rcl path uses rosidl String
                out.append("    char %s[%d]; /* mock-only fixed cap */" % (fname, MOCK_STRING_CAP))
            elif is_seq(ftype):
                elem = seq_elem(ftype)
                celem = PRIM_C[elem]  # sequences are always primitive at v0.12.1
                # mock-only: fixed 64-element array; rcl path uses rosidl Sequence
                out.append("    struct { %s data[%d]; uint32_t size; } %s; /* mock-only fixed cap */" % (
                    celem, MOCK_SEQ_CAP, fname))
            else:
                out.append("    %s %s;" % (field_ctype(ftype), fname))
        out.append("};")
        out.append("")
    out += ["#endif", "#endif", ""]
    return "\n".join(out)

def emit_forward_decls(msgs):
    out = []
    for name in toposort(msgs):
        cs, base = cident(name), name.replace("/", "__")
        out.append("int urbi_ros_marshal__%s(struct UVM *vm, UValue obj, struct %s *out);" % (base, cs))
        out.append("int urbi_ros_unmarshal__%s(struct UVM *vm, const struct %s *in, UValue *out);" % (base, cs))
    return "\n".join(out)

def emit_marshal(msgs):
    out = []
    for name in toposort(msgs):
        cs, fn = cident(name), "urbi_ros_marshal__" + name.replace("/", "__")
        out.append("int %s(struct UVM *vm, UValue obj, struct %s *out) {" % (fn, cs))
        for fname, ftype in msgs[name]:
            if ftype == "string":
                out.append('    { UValue _v = urbi_make_nil(); size_t _slen = 0;')
                out.append('      if (urbi_slot_get(vm, obj, "%s", %d, &_v) != 0) return -1;' % (fname, len(fname)))
                out.append('      { const char *_s = urbi_value_as_str(_v, &_slen);')
                out.append('        if (_s == NULL) { out->%s[0] = \'\\0\'; }' % fname)
                out.append('        else { strncpy(out->%s, _s, %d - 1U); out->%s[%d - 1] = \'\\0\'; } } }' % (
                    fname, MOCK_STRING_CAP, fname, MOCK_STRING_CAP))
            elif is_seq(ftype):
                elem = seq_elem(ftype)
                out.append('    { UValue _lst = urbi_make_nil(); int _n, _i;')
                out.append('      if (urbi_slot_get(vm, obj, "%s", %d, &_lst) != 0) return -1;' % (fname, len(fname)))
                out.append('      _n = urbi_list_len(vm, _lst);')
                out.append('      if (_n < 0) _n = 0;')
                out.append('      if (_n > %d) _n = %d;' % (MOCK_SEQ_CAP, MOCK_SEQ_CAP))
                out.append('      out->%s.size = (uint32_t)_n;' % fname)
                out.append('      for (_i = 0; _i < _n; _i++) {')
                out.append('        UValue _ev = urbi_list_get(vm, _lst, _i);')
                out.append('        out->%s.data[_i] = %s%s(_ev); } }' % (
                    fname, CCAST[elem], SLOT_READ[elem]))
            elif ftype in PRIM_C:
                out.append('    { UValue _v = urbi_make_nil();')
                out.append('      if (urbi_slot_get(vm, obj, "%s", %d, &_v) != 0) return -1;' % (fname, len(fname)))
                out.append('      out->%s = %s%s(_v); }' % (fname, CCAST[ftype], SLOT_READ[ftype]))
            else:
                nfn = "urbi_ros_marshal__" + ftype.replace("/", "__")
                out.append('    { UValue _v = urbi_make_nil();')
                out.append('      if (urbi_slot_get(vm, obj, "%s", %d, &_v) != 0) return -1;' % (fname, len(fname)))
                out.append('      if (%s(vm, _v, &out->%s) != 0) return -1; }' % (nfn, fname))
        out.append("    return 0;\n}")
    return "\n".join(out)

def emit_unmarshal(msgs):
    out = []
    for name in toposort(msgs):
        cs, fn = cident(name), "urbi_ros_unmarshal__" + name.replace("/", "__")
        out.append("int %s(struct UVM *vm, const struct %s *in, UValue *out) {" % (fn, cs))
        out.append('    struct UObject *o = urbi_ros_msg_alloc(vm, "%s");' % name)
        out.append("    if (o == NULL) return -1;")
        out.append("    UValue obj = urbi_make_object(o);")
        for fname, ftype in msgs[name]:
            if ftype == "string":
                out.append('    { size_t _slen = strlen(in->%s);' % fname)
                out.append('      UValue _sv = urbi_make_str_interned(vm, in->%s, _slen);' % fname)
                out.append('      if (urbi_slot_set(vm, obj, "%s", %d, _sv) != 0) return -1; }' % (fname, len(fname)))
            elif is_seq(ftype):
                elem = seq_elem(ftype)
                out.append('    { uint32_t _n = in->%s.size; uint32_t _i;' % fname)
                out.append('      UValue _lst = urbi_list_create(vm);')
                out.append('      if (_lst.kind == (uint8_t)UVAL_NIL) return -1;')
                out.append('      for (_i = 0; _i < _n && _i < %dU; _i++) {' % MOCK_SEQ_CAP)
                out.append('        if (urbi_list_append(vm, _lst, %s(in->%s.data[_i])) != 0) return -1; }' % (
                    MAKE[elem], fname))
                out.append('      if (urbi_slot_set(vm, obj, "%s", %d, _lst) != 0) return -1; }' % (fname, len(fname)))
            elif ftype in PRIM_C:
                out.append('    if (urbi_slot_set(vm, obj, "%s", %d, %s(in->%s)) != 0) return -1;' % (fname, len(fname), MAKE[ftype], fname))
            else:
                nfn = "urbi_ros_unmarshal__" + ftype.replace("/", "__")
                out.append('    { UValue _nv = urbi_make_nil();')
                out.append('      if (%s(vm, &in->%s, &_nv) != 0) return -1;' % (nfn, fname))
                out.append('      if (urbi_slot_set(vm, obj, "%s", %d, _nv) != 0) return -1; }' % (fname, len(fname)))
        out.append("    *out = obj; return 0;\n}")
    return "\n".join(out)

def emit_registry(msgs):
    order = toposort(msgs); out = []
    for name in order:
        base = name.replace("/", "__")
        out.append("static int _m_%s(struct UVM *vm, UValue o, void *p){return urbi_ros_marshal__%s(vm,o,(struct %s*)p);}" % (base, base, cident(name)))
        out.append("static int _u_%s(struct UVM *vm, const void *p, UValue *o){return urbi_ros_unmarshal__%s(vm,(const struct %s*)p,o);}" % (base, base, cident(name)))
    out.append("static const URosMsgType g_ros_types[] = {")
    for name in order:
        base = name.replace("/", "__")
        out.append('  { "%s", sizeof(struct %s), _m_%s, _u_%s },' % (name, cident(name), base, base))
    out.append("};")
    out.append("static const int g_ros_types_n = %d;" % len(order))
    out.append('const URosMsgType *urbi_ros_msg_lookup(const char *name){')
    out.append('  int i; for (i=0;i<g_ros_types_n;i++) if (urbi_streq(name, g_ros_types[i].name)) return &g_ros_types[i];')
    out.append('  return 0;\n}')
    out.append("int urbi_ros_msg_register_all(struct UVM *vm){")
    out.append("  if (vm == 0 || vm->ros_proto == 0) return -1;")
    out.append("  urbi_ros_msg__reset();")
    for name in order:
        slot = "msg__" + name.replace("/", "__")
        out.append('  { struct UObject *o = urbi_object_clone(vm, urbi_object_root(vm)); if(!o) return -1;')
        for fname, ftype in msgs[name]:
            out.append('    if (urbi_slot_set(vm, urbi_make_object(o), "%s", %d, urbi_make_nil())!=0) return -1;' % (fname, len(fname)))
        out.append('    urbi_ros_msg__record(vm, "%s", o);' % name)
        out.append('    { USymbol *sy=(USymbol*)ustr_intern(vm,"%s",%d); if(!sy) return -1; urbi_object_set_local_slot(vm,(struct UObject*)vm->ros_proto,sy,urbi_make_object(o)); } }' % (slot, len(slot)))
    out.append("  return 0;\n}")
    return "\n".join(out)

def emit_c(msgs):
    parts = [
        "/* GENERATED by tools/urbi-rosgen.py - do not edit. */",
        "#ifdef URBI_ENABLE_ROS2",
        "#include <string.h>  /* strlen / strncpy */",
        '#include "urbi/urbi.h"',
        '#include "urbi/types.h"',
        '#include "vm/uvm.h"',
        '#include "object/uobject.h"',
        '#include "value/uintern.h"',
        '#include "value/ulist_build.h"',
        '#include "ros/uros_msg.h"',
        '#include "ros/generated/ros_msgs.gen.h"',
        "",
        "/* Forward declarations: nested-message marshal/unmarshal are called",
        " * by reference before their definitions in toposort order. */",
        emit_forward_decls(msgs),
        "",
        emit_marshal(msgs),
        "",
        emit_unmarshal(msgs),
        "",
        emit_registry(msgs),
        "",
        "#else",
        "typedef int uros_translation_unit_not_empty;",
        "#endif /* URBI_ENABLE_ROS2 */",
        "",
    ]
    return "\n".join(parts)

def main():
    manifest, out_c, out_h = sys.argv[1], sys.argv[2], sys.argv[3]
    msgs = json.load(open(manifest))["messages"]
    open(out_h, "w").write(emit_header(msgs))
    open(out_c, "w").write(emit_c(msgs))

if __name__ == "__main__":
    main()
